-- ShowroomCiro — Funciones y vistas de lógica de negocio
-- Basado en docs/design.md (sección 2, "APIs principales"), docs/prd.md ("Reportes") y
-- docs/tasks.md (Módulo 2). Requiere 0001_init_schema.sql y 0002_rls_policies.sql ya aplicadas.
--
-- Contenido:
--   0. Ajustes de schema: se quita `cuentas.estado`, se agrega `ventas.caja_id` y
--      `productos.codigo`.
--   1. Helpers de fecha local (Argentina).
--   2. Trigger BEFORE INSERT en `variantes` que genera el SKU automáticamente.
--   3. Función RPC `cerrar_caja(caja_id, monto_contado)`.
--   4. Vista `cuentas_vista` con saldo y estado calculados al vuelo.
--   5. Reportes (solo Dueño/a): `reportes_ventas_vista`, `reportes_top_productos_vista`,
--      `reportes_cuentas_pendientes_vista` y RPCs para rangos de fechas arbitrarios.
--
-- Zona horaria: Supabase corre en UTC. Todo lo que dependa de "hoy" o de agrupar por día
-- se calcula con la hora de Argentina; si no, a partir de las 21:00 locales CURRENT_DATE ya
-- es "mañana" (una cuenta pasaría a vencida 3 h antes y las ventas de la noche caerían en
-- el día siguiente).

-- ============================================================================
-- 0. Ajustes de schema
-- ============================================================================

-- cuentas.estado ya no se guarda: `cuentas_vista` es la única fuente de verdad del estado.
alter table public.cuentas drop constraint if exists chk_cuentas_estado;
alter table public.cuentas drop column if exists estado;

-- Cada venta queda vinculada a la caja que estaba abierta cuando se hizo.
-- NOT NULL sin default: si `ventas` ya tuviera filas cargadas a mano, este ALTER falla
-- (hay que asignarles una caja o borrarlas antes). El seed no carga ventas.
alter table public.ventas
  add column caja_id uuid not null references public.cajas (id);

create index idx_ventas_caja_id on public.ventas (caja_id);

-- Número correlativo legible del producto (1, 2, 3...), usado en el SKU (SC-001-...).
-- `productos.id` sigue siendo el uuid y la PK; `codigo` es solo un identificador humano.
-- "by default" permite cargar un código a mano si hiciera falta (ej. migrar datos viejos).
alter table public.productos
  add column codigo integer generated by default as identity;

alter table public.productos
  add constraint uq_productos_codigo unique (codigo);

